/**
 * Раскладка верхней панели, когда пункты в неё не помещаются.
 *
 * Горизонтальная прокрутка внутри полосы высотой 46px — это молчаливая потеря
 * навигации: на 1024px за краем оказывались «Сообщество», «Аудит» и
 * «Настройки», а единственным признаком служила тонкая полоска прокрутки.
 * Вместо этого лишние пункты уезжают в меню «Ещё»: панель остаётся в одну
 * строку, и ни один раздел не становится недостижимым.
 *
 * Ширины измеряет компонент, а решение принимает эта функция — так его можно
 * проверить тестами, не поднимая браузер: в jsdom нет вёрстки и все ширины
 * равны нулю.
 */

/** Сколько пунктов оставить в полосе; остальные уходят в «Ещё». */
export function fitNavEntries(
  widths: readonly number[],
  available: number,
  moreWidth: number,
): number {
  // Ширины ещё не измерены (первый серверный рендер): показываем всё. Иначе
  // панель успела бы мигнуть свёрнутой до того, как измерение случится.
  if (available <= 0) return widths.length;

  const total = widths.reduce((sum, w) => sum + w, 0);
  if (total <= available) return widths.length;

  // Место под саму кнопку «Ещё» резервируется заранее: без этого последний
  // влезший пункт вытолкнул бы её за край и она стала бы недоступна.
  const budget = available - moreWidth;
  let used = 0;
  let fit = 0;
  for (const width of widths) {
    if (used + width > budget) break;
    used += width;
    fit += 1;
  }
  return fit;
}
