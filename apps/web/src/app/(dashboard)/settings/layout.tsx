import type { ReactNode } from 'react';
import { PageContainer } from '@/components/ui';

/**
 * Каркас раздела «Настройки»: одна ширина содержимого на все его страницы.
 *
 * Ширина выбрана здесь, а не каждой страницей, потому что раздел — это два
 * десятка экранов, между которыми оператор ходит через одно и то же меню:
 * страница, поставившая себе собственный `max-w`, заставляет содержимое
 * прыгать по горизонтали при каждом переходе (дизайн-система, §3).
 *
 * Взята `reading` (max-w-3xl) — та, которую §3 и назначает настройкам.
 * Раньше здесь стояла `wide` из опасения, что таблицам раздела (участники
 * роли, токены, снимки бэкапов) будет тесно. На проверке оказалось наоборот:
 * в `wide` таблицы всё равно вмещались, зато сгруппированные строки
 * растягивались на всю ширину и подпись с значением расходились к
 * противоположным краям — приём inset grouped таблиц Apple, рассчитанный на
 * строку в 350pt, а не в 1150px. В `reading` строка читается как строка, а
 * ни одна таблица раздела не перестала помещаться.
 *
 * Заголовок первого уровня остаётся у страниц: у каждой из них он свой, в
 * отличие от раздела «Сервер», где `<h1>` — это имя одного объекта.
 */
export default function SettingsLayout({ children }: { children: ReactNode }) {
  return <PageContainer width="reading">{children}</PageContainer>;
}
